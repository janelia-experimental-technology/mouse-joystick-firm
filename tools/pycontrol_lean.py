#!/usr/bin/env python3
"""Generate the lean copies of this repository's pyControl files for the pyboard.

    pixi run -e pycontrol python tools/pycontrol_lean.py [--check]

The pyboard's internal flash is 95 KB and the pyControl framework takes half
of it. The files in `pycontrol/devices`, `pycontrol/hardware_definitions` and
`pycontrol/tasks` are written to be read: on 2026-10-06 they were 60 % prose,
and the first Gate E upload failed with "Insufficient space on pyboard
filesystem" (36 KB free, 60 KB to send). pyControl uploads source files
verbatim, so the deliverable for the board is a copy with the comments and
docstrings removed -- same code, same names, same behaviour -- written to
`pycontrol/dist/<folder>/` by this script. `pycontrol-link` points the
pyControl checkout at `dist/`, `pycontrol_run.py` regenerates it before every
run, and `pycontrol/tests/test_lean.py` imports what it produces.

The source files stay the only thing anyone edits. `dist/` is generated and
ignored by git; the rig delivery ships `dist/` files alongside the README that
carries the prose.

Comments are not part of the syntax tree, so unparsing the parsed module
drops them; docstrings are expression statements that this removes (a body
left empty gets `pass`). A side effect that matters: pyControl decides which
device files to upload by substring-matching class names against file TEXT,
comments included, and a comment naming another driver's class pulled a 9 KB
driver onto the board. Lean files mention only what they use.
"""
import argparse
import ast
import sys
from pathlib import Path

FOLDERS = ("devices", "hardware_definitions", "tasks")


def _strip_docstrings(tree):
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            body = node.body
            if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant) \
                    and isinstance(body[0].value.value, str):
                del body[0]
            if not body:
                body.append(ast.Pass())
    return tree


def lean_source(src, origin):
    tree = _strip_docstrings(ast.parse(src))
    header = "# Generated from %s by tools/pycontrol_lean.py: comments and docstrings\n# removed for the pyboard's flash. Edit the source, not this file.\n" % origin
    return header + ast.unparse(tree) + "\n"


def generate(root, out_root=None, verbose=True):
    """Write dist/<folder>/*.py for every source file; return [(src, dst, bytes_in, bytes_out)]."""
    root = Path(root)
    out_root = Path(out_root) if out_root else root / "pycontrol" / "dist"
    results = []
    for folder in FOLDERS:
        src_dir = root / "pycontrol" / folder
        dst_dir = out_root / folder
        dst_dir.mkdir(parents=True, exist_ok=True)
        for src in sorted(src_dir.glob("*.py")):
            text = src.read_text(encoding="utf-8")
            lean = lean_source(text, "pycontrol/%s/%s" % (folder, src.name))
            dst = dst_dir / src.name
            dst.write_text(lean, encoding="utf-8")
            results.append((src, dst, len(text.encode()), len(lean.encode())))
            if verbose:
                print("%-45s %6d -> %5d bytes" % ("dist/%s/%s" % (folder, src.name), results[-1][2], results[-1][3]))
        # Stale outputs whose source is gone would be uploaded by name: remove them.
        for stale in dst_dir.glob("*.py"):
            if not (src_dir / stale.name).exists():
                stale.unlink()
    (out_root / "README.md").write_text(
        "Generated by tools/pycontrol_lean.py from pycontrol/{devices,hardware_definitions,tasks}: "
        "the same code with comments and docstrings removed, for the pyboard's 95 KB flash. "
        "Do not edit; do not commit.\n", encoding="utf-8")
    return results


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="also compile every output")
    args = ap.parse_args()
    root = Path(__file__).resolve().parents[1]
    results = generate(root)
    total_in = sum(r[2] for r in results)
    total_out = sum(r[3] for r in results)
    print("total %d -> %d bytes" % (total_in, total_out))
    if args.check:
        for _, dst, _, _ in results:
            compile(dst.read_text(encoding="utf-8"), str(dst), "exec")
        print("all outputs compile")


if __name__ == "__main__":
    sys.exit(main())
