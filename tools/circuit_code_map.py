#!/usr/bin/env python3
"""Write docs/circuit-code-map.md: which circuit each piece of firmware talks to.

Reads the rig's component registry (mouse-joysticks-mech, atlas/components.yaml),
the board's manifest and source (mouse-joystick-pcb, kicad/board-manifest.yaml
and kicad/board.yaml) from sibling checkouts, and writes one table row per
registry entry that names firmware: the part, the board connector, the
schematic block, the nets the block meets and their GPIOs, the firmware files,
the protocol verbs and events, and the bring-up procedure. A second table
inverts it: firmware file -> parts. Nothing in the output is written by hand;
edit the registry or the board records and run this again.

    python3 tools/circuit_code_map.py [--mech ../mouse-joysticks-mech] [--pcb ../mouse-joystick-pcb]
"""
import argparse, pathlib, re, sys
import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPOS = {
    "mouse-joystick-pcb": ("https://github.com/peterpolidoro/mouse-joystick-pcb", "v1.0"),
    "mouse-joystick-firm": ("https://github.com/peterpolidoro/mouse-joystick-firm", "v1.0.0"),
    "mouse-joysticks-mech": ("https://github.com/peterpolidoro/mouse-joysticks-mech", "main"),
}


def url(repo, path, tag=None):
    base, default = REPOS[repo]
    return f"{base}/blob/{tag or default}/{path}"


def link(repo, path):
    return f"[`{path}`]({url(repo, path)})"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mech", default=str(ROOT.parent / "mouse-joysticks-mech"))
    ap.add_argument("--pcb", default=str(ROOT.parent / "mouse-joystick-pcb"))
    a = ap.parse_args()
    reg = yaml.safe_load(open(pathlib.Path(a.mech) / "atlas/components.yaml"))
    manifest = yaml.safe_load(open(pathlib.Path(a.pcb) / "kicad/board-manifest.yaml"))
    board = yaml.safe_load(open(pathlib.Path(a.pcb) / "kicad/board.yaml"))
    nets = {k.lstrip("/"): v for k, v in (board.get("nets") or {}).items()}
    placements = {f"{p['parent'].lstrip('/')}/{p['name']}": p for p in manifest["placements"]}

    def gpios_of(instance):
        p = placements.get(instance)
        if not p:
            return []
        out = []
        for port, net in sorted(p.get("connections", {}).items()):
            if not isinstance(net, str):
                continue  # an open port is recorded as a mapping with its reason
            n = nets.get(net)
            if n and n.get("gpio"):
                out.append(f"`{net}` {n['gpio']}")
        return out

    rows = []
    for e in reg:
        fw = e.get("firmware") or {}
        if not fw and not e.get("block_instance"):
            continue
        conns = ", ".join(f"`{c['connector']}`" for c in e.get("connects_to", []) if c.get("board") == "mouse-joystick-pcb") or ""
        block = e.get("block_instance", "")
        block_s = f"`{block.split('/')[-1]}` in sheet `{block.split('/')[0]}`" if block else ""
        files = ", ".join(link("mouse-joystick-firm", f) for f in fw.get("files", []))
        proto = ", ".join(f"`{p}`" for p in fw.get("protocol", []))
        bring = ", ".join(link("mouse-joystick-firm", b) for b in fw.get("bringup", []))
        rows.append((e, conns, block_s, gpios_of(block) if block else [], files, proto, bring))

    L = ["# Circuit-to-code map", "",
         "Which part of the rig each piece of this firmware talks to, through which",
         "board connector and schematic block, over which nets and GPIOs, and which",
         "protocol verbs and events the host sees for it. Generated by",
         "`tools/circuit_code_map.py` from the rig's component registry",
         f"({link('mouse-joysticks-mech', 'atlas/components.yaml')}) and the board's records",
         f"({link('mouse-joystick-pcb', 'kicad/board-manifest.yaml')}, {link('mouse-joystick-pcb', 'kicad/board.yaml')});",
         "do not edit, change those and run the script. GPIO numbers are the board's",
         f"as built at `v1.0` (`src/BoardPins.hpp` carries the same numbers with their history).", "",
         "## By part", ""]
    for e, conns, block_s, gpios, files, proto, bring in rows:
        L += [f"### {e['name']}", ""]
        if e.get("description"):
            L += [e["description"].strip(), ""]
        L += ["| | |", "| --- | --- |"]
        if conns:
            L.append(f"| Board connector | {conns} |")
        if block_s:
            L.append(f"| Schematic block | {block_s} |")
        if gpios:
            L.append(f"| Nets and GPIOs | {', '.join(gpios)} |")
        if files:
            L.append(f"| Firmware | {files} |")
        if proto:
            L.append(f"| Protocol | {proto} |")
        if bring:
            L.append(f"| Proved by | {bring} |")
        if (e.get("firmware") or {}).get("notes"):
            L.append(f"| Note | {e['firmware']['notes']} |")
        L.append("")
    by_file = {}
    for e, *_ in rows:
        for f in (e.get("firmware") or {}).get("files", []):
            by_file.setdefault(f, []).append(e["name"])
    L += ["## By firmware file", "", "| File | Parts it touches |", "| --- | --- |"]
    for f in sorted(by_file):
        L.append(f"| {link('mouse-joystick-firm', f)} | {', '.join(by_file[f])} |")
    L += ["", "Files that touch no rig part and are not listed: the protocol codec and state",
          "machine (`src/Protocol.hpp`, `src/ProtocolBoard.hpp`), the power sequencing",
          "(`src/PowerSequence.hpp`, `src/SafeState.hpp`), the self test and the pyControl",
          "link; [the architecture page](architecture.md) places them."]
    out = ROOT / "docs/circuit-code-map.md"
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(rows)} parts, {len(by_file)} files")


if __name__ == "__main__":
    sys.exit(main())
