#!/usr/bin/env python3
"""Write docs/pycontrol-api.md from the device class's own docstrings.

Parses pycontrol/devices/mouse_joystick.py with `ast` (never imports it: it
is MicroPython and needs pyControl) and lists every public method of
`MouseJoystick` with its signature, the protocol verb it sends (read from the
`_send("verb", ...)` call in its body) and the first paragraph of its
docstring. Regenerate after editing the device class.

    python3 tools/pycontrol_api_doc.py
"""
import ast, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "pycontrol/devices/mouse_joystick.py"


def verb_of(fn):
    for node in ast.walk(fn):
        if isinstance(node, ast.Call) and getattr(node.func, "attr", None) == "_send" and node.args:
            a = node.args[0]
            if isinstance(a, ast.Constant):
                return a.value
    return ""


def signature(fn):
    args = fn.args
    parts = []
    defaults = [None] * (len(args.args) - len(args.defaults)) + list(args.defaults)
    for arg, d in zip(args.args, defaults):
        if arg.arg == "self":
            continue
        parts.append(arg.arg if d is None else f"{arg.arg}={ast.unparse(d)}")
    if args.vararg:
        parts.append("*" + args.vararg.arg)
    if args.kwarg:
        parts.append("**" + args.kwarg.arg)
    return f"{fn.name}({', '.join(parts)})"


def first_paragraph(doc):
    if not doc:
        return ""
    para = doc.strip().split("\n\n")[0]
    return " ".join(line.strip() for line in para.splitlines())


def main():
    tree = ast.parse(SRC.read_text())
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "MouseJoystick")
    module_doc = first_paragraph(ast.get_docstring(tree))
    rows = []
    for fn in cls.body:
        if isinstance(fn, ast.FunctionDef) and not fn.name.startswith("_"):
            rows.append((signature(fn), verb_of(fn), first_paragraph(ast.get_docstring(fn))))
    L = ["# The pyControl device class", "",
         f"`MouseJoystick` in `pycontrol/devices/mouse_joystick.py`, as pyControl's task sees it.",
         "Generated by `tools/pycontrol_api_doc.py` from the class's own docstrings;",
         "do not edit, change the class and run the script. The full account of the",
         "host side, the controller it needs and how it is delivered is",
         "[`pycontrol/README.md`](../pycontrol/README.md); the wire format is the",
         "[UART protocol](https://github.com/peterpolidoro/mouse-joystick-pcb/blob/v1.0/docs/uart-protocol.md).", "",
         module_doc, "",
         "Every command method sends one line and returns its sequence number; the",
         "board's `ack` or `nak` for that number, and every event, come back through",
         "`poll()` when the port's event fires. A task matches the `ack` to the number",
         "it is waiting for, as the rig's trial task does.", "",
         "| Method | Sends | What it does |", "| --- | --- | --- |"]
    for sig, verb, doc in rows:
        L.append(f"| `{sig}` | {('`' + verb.upper() + '`') if verb else ''} | {doc} |")
    L += ["", "Methods whose names begin with an underscore are internal."]
    out = ROOT / "docs/pycontrol-api.md"
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(rows)} methods")


if __name__ == "__main__":
    sys.exit(main())
